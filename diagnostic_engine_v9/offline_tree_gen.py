"""Offline decision-tree generator (Option 1, single-pass) — offline_tree_generator_spec.

Drives the REAL engine in `deterministic` selection mode at the shipped config
(misconception_conditional_extra = 0), walking BOTH answer outcomes at every node,
deduplicating on the single-pass state key (5.3), bounded at the grade budget.
The tree is generated by the engine production runs, never a reimplementation (5.1).

Checkpoint 1 builds one grade and reports: node/leaf count, serialized size,
the determinism check (5.5), the merge soundness check (do paths that merge on the
single-pass key carry identical misconception counts?), and the posterior-bucketing
sensitivity probe (open point 1).
"""
